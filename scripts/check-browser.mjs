import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import mongoose from 'mongoose';
import { randomUUID } from 'node:crypto';
import { createApp } from '../server/app.js';
import { Product, Post } from '../server/models.js';
import { initialProducts, initialPosts } from '../shared/catalog.js';
import { isolateTestUploads, removeTestDirectory } from './test-support.mjs';

const databaseName = `masaloo_test_storefront_${randomUUID().replaceAll('-', '')}`;
const uploadDirectory = await isolateTestUploads();
process.env.NODE_ENV = 'test';
process.env.JWT_SECRET = 'storefront-test-only-secret-at-least-thirty-two-characters';
await mongoose.connect(`mongodb://127.0.0.1:27017/${databaseName}`, { serverSelectionTimeoutMS: 5000 });
const server = createApp().listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
process.env.CLIENT_ORIGIN = base;
let browser;
try {
  await Promise.all([Product.init(), Post.init()]);
  await Product.insertMany(initialProducts); await Post.insertMany(initialPosts);
  browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
  const page = await context.newPage(), errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await mkdir('artifacts', { recursive: true });
  await page.goto(base);
  await page.getByRole('heading', { name: 'Pure Spices. Rich Taste.' }).waitFor();
  await page.locator('.product-card').first().waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'artifacts/home-desktop.png', fullPage: true });
  const brokenImages = await page.locator('img').evaluateAll(images => images.filter(img => img.complete && img.naturalWidth === 0).map(img => img.src));
  assert.deepEqual(brokenImages, [], 'All home images load');
  await page.getByRole('link', { name: 'Shop our spices' }).click();
  await page.getByRole('heading', { name: 'A world of flavour. A pinch away.' }).waitFor();
  await page.locator('.product-card').first().waitFor();
  await page.getByRole('textbox', { name: 'Search spices', exact: true }).fill('haldi');
  await page.waitForFunction(() => document.querySelectorAll('.product-card').length === 1);
  await page.getByRole('button', { name: 'Add Haldi Powder to bag' }).click();
  await page.getByRole('button', { name: 'Open bag, 1 items' }).click();
  await page.getByRole('dialog', { name: 'Your spice bag' }).waitFor();
  await page.getByRole('button', { name: 'Add one Haldi Powder' }).click();
  await page.getByRole('button', { name: 'Continue to checkout' }).click();
  await page.getByText('Checkout is coming soon', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Close dialog' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Open bag, 2 items' }).waitFor();
  console.log('PASS: shop search, cart addition, quantity, checkout notice, and cart persistence.');
  await page.getByRole('button', { name: 'Clear search' }).click();
  await page.getByRole('button', { name: 'Whole spices', exact: true }).click();
  await page.waitForFunction(() => document.querySelectorAll('.product-card').length === 1);
  await page.locator('.product-card h3').getByText('Whole Cumin').click();
  await page.getByRole('heading', { name: 'Whole Cumin', exact: true }).waitFor();
  console.log('PASS: category filtering and product detail route.');
  await page.goto(`${base}/about`);
  await page.getByRole('heading', { name: 'Some stories begin in the kitchen.' }).waitFor();
  await page.goto(`${base}/contact`);
  await page.getByRole('heading', { name: 'Good conversations. Great beginnings.' }).waitFor();
  await page.goto(`${base}/blog`);
  await page.locator('.blog-card').first().waitFor();
  await page.locator('.blog-card h3').first().click();
  await page.locator('.article-body').waitFor();
  await page.goto(`${base}/admin`);
  await page.getByRole('heading', { name: 'Admin login' }).waitFor();
  console.log('PASS: About, Contact, journal/article, and protected admin entry.');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  await page.locator('.product-card').first().waitFor();
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: 'artifacts/home-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Home fits mobile width');
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('link', { name: 'Shop', exact: true }).click();
  await page.locator('.product-card').first().waitFor();
  await page.screenshot({ path: 'artifacts/shop-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Shop fits mobile width');
  await page.goto(`${base}/contact`);
  await page.screenshot({ path: 'artifacts/contact-mobile.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'Contact fits mobile width');
  await page.getByLabel('Your name *').fill('Test visitor');
  await page.getByLabel('Email address *').fill('invalid-email');
  await page.getByRole('button', { name: 'Send your message' }).click();
  assert.equal(await page.getByLabel('Email address *').evaluate(el => el.validity.valid), false);
  assert.deepEqual(errors, [], 'No browser runtime errors');
  console.log('PASS: mobile navigation, page widths, contact validation, and no runtime errors.');
  console.log('Screenshots saved in artifacts/.');
} finally {
  await browser?.close();
  if (!mongoose.connection.name.startsWith('masaloo_test_storefront_')) throw new Error('Refusing to clean up a non-test database.');
  await mongoose.connection.dropDatabase(); await mongoose.disconnect();
  await new Promise(resolve => server.close(resolve));
  await removeTestDirectory(uploadDirectory);
}
