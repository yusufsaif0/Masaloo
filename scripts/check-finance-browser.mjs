  assert.equal((await Sale.findOne({ id: shopSale.id })).paidPaise, 15010);
  await page.getByRole('button', { name: 'Add previous udhari', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Add previous udhari' });
  await dialog.getByLabel('Outstanding amount (₹)', { exact: true }).fill('75.25');
  await dialog.getByRole('button', { name: 'Add balance', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('cell', { name: 'Previous udhari', exact: true }).waitFor();
  const opening = await Sale.findOne({ kind: 'opening_balance' });
  await page.getByRole('button', { name: `Open record ${opening.reference}`, exact: true }).click();
  await page.getByRole('button', { name: 'Record repayment', exact: true }).click();
  await page.getByRole('button', { name: 'Save repayment', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Sale & payment history' });
  await dialog.getByText('Paid', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Close dialog' }).click();
  await page.locator('.finance-ledger-stats article').nth(2).getByText('₹50.10', { exact: true }).waitFor();
