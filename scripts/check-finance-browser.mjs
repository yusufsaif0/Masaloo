  await dialog.getByLabel('Unit price 1', { exact: true }).fill('100.10');
  await dialog.getByLabel('Payment status', { exact: true }).selectOption('partial');
  await dialog.getByLabel('Amount received (₹)', { exact: true }).fill('100');
  await dialog.getByRole('button', { name: 'Save sale', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('cell', { name: 'Ravi Trading', exact: false }).waitFor();
  const shopSale = await Sale.findOne({ channel: 'shop', kind: 'sale' });
  assert.equal(shopSale.totalPaise, 20020);
  assert.equal(shopSale.paidPaise, 10000);
  assert.equal(await LedgerCustomer.countDocuments({ name: 'Ravi Trading' }), 1);
  await page.getByRole('button', { name: 'Record sale', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Record a sale' });
  await dialog.getByLabel('Sales channel', { exact: true }).selectOption('online');
  await dialog.getByLabel('Buyer name (optional)', { exact: true }).fill('Online buyer');
  await dialog.getByLabel('Product 1', { exact: true }).selectOption('mirch-powder');
  await dialog.getByLabel('Quantity 1', { exact: true }).fill('3');
  await dialog.getByLabel('Unit price 1', { exact: true }).fill('80.05');
  await dialog.getByLabel('Payment method', { exact: true }).selectOption('upi');
  await dialog.getByLabel('Order / receipt reference (optional)', { exact: true }).fill('WEB-TEST-1');
  await dialog.getByRole('button', { name: 'Save sale', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  await page.getByRole('cell', { name: 'Online buyer', exact: false }).waitFor();
  assert.equal(await Sale.countDocuments({ kind: 'sale' }), 2);
  await page.locator('.finance-stats article').first().getByText('₹440.35', { exact: true }).waitFor();
  const search = page.getByLabel('Find a sale', { exact: true });
  await search.pressSequentially('Ravi', { delay: 120 });
  await page.waitForFunction(() => document.querySelectorAll('.finance-module tbody tr').length === 1);
  assert.equal(await search.inputValue(), 'Ravi');
  assert.equal(await search.evaluate(element => element === document.activeElement), true, 'Search retains focus while reports update');
  await search.fill('');
  await page.waitForFunction(() => document.querySelectorAll('.finance-module tbody tr').length === 2);
