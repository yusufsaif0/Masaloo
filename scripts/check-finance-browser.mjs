  await tab('Udhari ledger').click();
  await page.getByRole('button', { name: 'Open ledger for Ravi Trading' }).click();
  await page.getByRole('heading', { name: 'Ravi Trading', exact: true }).waitFor();
  await page.getByRole('button', { name: `Open record ${shopSale.reference}`, exact: true }).click();
  await page.getByRole('button', { name: 'Record repayment', exact: true }).click();
  dialog = page.getByRole('dialog', { name: 'Record a repayment' });
