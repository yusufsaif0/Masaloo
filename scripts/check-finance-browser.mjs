  console.log('PASS: partial repayments, opening udhari, settlement, and customer payment history.');

  await tab('Monthly sales').click();
  await page.locator('.finance-stats article').first().getByText('₹440.35', { exact: true }).waitFor();
  await page.locator('.finance-stats article').nth(1).getByText('₹465.50', { exact: true }).waitFor();
  await page.locator('.finance-chart button').nth(Number(indiaToday().slice(-2)) - 1).click();
  await page.locator('.finance-chart-detail').getByText('Sales ₹440.35', { exact: true }).waitFor();
  const downloadReady = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click();
  const download = await downloadReady;
  const csv = await readFile(await download.path(), 'utf8');
  assert.match(csv, /440\.35/);
  assert.match(csv, /465\.50/);
  assert.match(download.suggestedFilename(), /^monthly-sales-/);
  await page.screenshot({ path: 'artifacts/monthly-sales-desktop.png', fullPage: true });
  console.log('PASS: monthly chart, payment-date collections, and downloaded CSV values.');

  await tab('Top products').click();
  await page.locator('.finance-module tbody tr').first().getByText('Mirch Powder', { exact: true }).waitFor();
